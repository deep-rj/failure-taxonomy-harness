def test_invariant_milestones_strictly_increasing():
    """Present milestone indices are strictly increasing."""
    steps = [
        step(1, LEFT, (2, 2), 3),
        step(2, LEFT, (2, 2), 2),
        step(3, PICKUP, (2, 2), 2, carrying=True),
        step(4, LEFT, (2, 2), 1, carrying=True),
        step(5, LEFT, (2, 2), 0, carrying=True),
        step(6, TOGGLE, (2, 2), 0, carrying=True, door_locked=False, door_open=True),
        step(7, FORWARD, (3, 2), 0, carrying=True, door_locked=False, door_open=True),
        step(8, FORWARD, (4, 2), 0, carrying=True, door_locked=False, door_open=True),
        step(9, RIGHT, (4, 2), 1, carrying=True, door_locked=False, door_open=True),
        step(10, FORWARD, (4, 3), 1, carrying=True, door_locked=False, door_open=True),
        step(
            11,
            FORWARD,
            (4, 4),
            1,
            carrying=True,
            door_locked=False,
            door_open=True,
            terminated=True,
            reward=0.802,
        ),
    ]
    predicates = compute_predicates(steps)
    present = [
        predicates["key_picked_step"],
        predicates["door_unlocked_step"],
        predicates["crossed_step"],
        predicates["goal_step"],
    ]
    assert all(a < b for a, b in itertools.pairwise(present))
