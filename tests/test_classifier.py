"""Classifier unit tests over hand-constructed milestone/predicate sets.

Per failure_spec.md §11: these cases must be authored by hand against the
spec (§5 classes, precedence rule), not generated by inspecting the
classifier implementation -- a model asked to test its own classifier
writes cases it already passes.

Scope: milestones (key_picked_step, door_unlocked_step, crossed_step,
goal_step) + flags + outcome (success/terminated/truncated) -> failure_class.
Does NOT cover raw-trajectory -> milestone computation -- see
test_predicates.py for that half.

classify()'s input is built from two helpers in helpers.py:
  - `milestones()` -- the §6 milestones + §7 flags. Same builder
    test_predicates.py uses for compute_predicates()'s expected output; the
    shape is identical whether it's arriving as that function's output or
    classify()'s input.
  - `outcome()` -- the minimal success/terminated/truncated bundle classify()
    needs to guard its "applies to failed episodes only" precondition (§5).
    Not the full §8 per-episode record -- total_steps/final_reward play no
    role in classification.

e.g.:
    milestones()                          # nothing happened: all None/0
    milestones(key_picked=3)              # only key_picked_step set
    milestones(key_picked=3, key_dropped=1)
    outcome(truncated=True)               # failed via timeout
    outcome(success=True, terminated=True)  # succeeded -- classify() should reject this
"""

from helpers import milestones, outcome

from failure_taxonomy_harness.classifier import FailureClass, classify

# --- One per failure class (§5), precedence ascending -----------------------


def test_class_never_picked_key():
    """Class 1: NEVER_PICKED_KEY — key_picked_step is None."""
    assert classify(milestones(), outcome(truncated=True)) == FailureClass.NEVER_PICKED_KEY


def test_class_never_unlocked_door():
    """Class 2: NEVER_UNLOCKED_DOOR — key_picked_step set, door_unlocked_step None."""
    record = milestones(key_picked=3)
    assert classify(record, outcome(truncated=True)) == FailureClass.NEVER_UNLOCKED_DOOR


def test_class_never_crossed_door():
    """Class 3: NEVER_CROSSED_DOOR — door_unlocked_step set, crossed_step None."""
    record = milestones(key_picked=3, door_unlocked=6)
    assert classify(record, outcome(truncated=True)) == FailureClass.NEVER_CROSSED_DOOR


def test_class_never_reached_goal():
    """Class 4: NEVER_REACHED_GOAL — crossed_step set, goal_step None."""
    record1 = milestones(key_picked=3, door_unlocked=6, crossed=8)
    assert classify(record1, outcome(truncated=True)) == FailureClass.NEVER_REACHED_GOAL


def test_class_reached_goal():
    """Class 5: SUCCESSFUL / REACHED GOAL - shouldn't be classified as a failure"""
    record = milestones(key_picked=3, door_unlocked=6, crossed=8, goal=12)
    assert classify(record, outcome(success=True, terminated=True)) == FailureClass.UNCLASSIFIED


# --- Precedence / mutual exclusivity (§5) ------------------------------------


def test_precedence_first_unmet_milestone_wins():
    """When multiple milestones are unmet, the earliest stage in the chain
    determines the class -- not the latest, not all of them.

    key_picked_step is left None while door_unlocked_step and crossed_step
    are (unrealistically, for a real trajectory) set anyway -- classify()
    must still walk the chain in order and stop at the first unmet stage,
    not be misled by a later milestone appearing set.
    """
    record = milestones(door_unlocked=6, crossed=8)
    assert classify(record, outcome(truncated=True)) == FailureClass.NEVER_PICKED_KEY


# --- Coverage (§10, §11) ------------------------------------------------------


def test_coverage_no_unclassified():
    """Classifier must never return UNCLASSIFIED for a failed episode."""
    records = [
        milestones(),
        milestones(key_picked=3),
        milestones(key_picked=3, door_unlocked=6),
        milestones(key_picked=3, door_unlocked=6, crossed=8),
    ]
    for record in records:
        assert classify(record, outcome(truncated=True)) != FailureClass.UNCLASSIFIED
